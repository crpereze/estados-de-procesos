import test from 'node:test'
import assert from 'node:assert/strict'
import { advanceSimulation, resetSimulation, simulationReducer, MAX_PROCESSES } from '../src/simulation.ts'
const process = (pid, overrides = {}) => ({ pid, name: 'worker', state: 'ready', total: 7, remaining: 7, arrival: 0, quantumUsed: 0, ioAt: null, ioDuration: 2, ioRemaining: 0, ...overrides })
const session = (...processes) => ({ ...resetSimulation(42), processes, events: [] })
test('CPU completion removes process permanently and records actual work', () => {
  let state = session(process(101, { total: 4, remaining: 4 }))
  for (let i = 0; i < 4; i++) state = advanceSimulation(state)
  assert.equal(state.completed, 1)
  assert.equal(state.processes.length, 0)
  assert.equal(state.busyTicks, 4)
  state = advanceSimulation(state)
  assert.equal(state.timeline.at(-1).pid, null)
  assert.equal(state.completed, 1)
})
test('Round Robin rotates FIFO exactly at the quantum boundary', () => {
  let state = session(process(101), process(102))
  for (let i = 0; i < 3; i++) state = advanceSimulation(state)
  assert.equal(state.processes.find(p => p.pid === 101).state, 'ready')
  assert.equal(state.processes.find(p => p.pid === 102).state, 'running')
  assert.deepEqual(state.timeline.map(t => t.pid), [101, 101, 101])
  assert.equal(advanceSimulation(state).timeline.at(-1).pid, 102)
})
test('I/O takes full duration; all blocked processes cause IDLE ticks and recover', () => {
  let state = session(process(101, { ioAt: 1 }))
  state = advanceSimulation(state)
  assert.equal(state.processes[0].state, 'blocked')
  assert.equal(state.processes[0].ioRemaining, 2)
  state = advanceSimulation(state)
  assert.equal(state.processes[0].ioRemaining, 1)
  state = advanceSimulation(state)
  assert.equal(state.processes[0].state, 'running')
  assert.deepEqual(state.timeline.map(t => t.pid), [101, null, null])
  assert.equal(advanceSimulation(state).processes[0].remaining, 5)
})
test('I/O wins over quantum expiry and completion wins over both', () => {
  let state = session(process(101, { ioAt: 3 }))
  for (let i = 0; i < 3; i++) state = advanceSimulation(state)
  assert.equal(state.processes[0].state, 'blocked')
  state = advanceSimulation(session(process(101, { total: 1, remaining: 1, ioAt: 1 })))
  assert.equal(state.completed, 1)
  assert.equal(state.processes.length, 0)
})
test('paused timers do nothing, manual step advances once and pauses, reset clears history', () => {
  const initial = resetSimulation(42)
  assert.equal(simulationReducer(initial, { type: 'clock' }), initial)
  const stepped = simulationReducer({ ...initial, active: true }, { type: 'step' })
  assert.equal(stepped.tick, 1)
  assert.equal(stepped.active, false)
  const reset = simulationReducer(stepped, { type: 'reset', value: 58 })
  assert.equal(reset.tick, 0)
  assert.equal(reset.busyTicks, 0)
  assert.equal(reset.completed, 0)
  assert.deepEqual(reset.timeline, [])
  assert.ok(reset.processes.every(p => p.remaining === p.total && p.state === 'ready'))
})
test('engine is immutable and deterministic', () => {
  const before = resetSimulation(42)
  const snapshot = structuredClone(before)
  assert.deepEqual(advanceSimulation(before), advanceSimulation(before))
  assert.deepEqual(before, snapshot)
})
test('randomized sessions preserve invariants, metrics, cap and bounded history', () => {
  for (let seed = 1; seed <= 30; seed++) {
    let state = { ...resetSimulation(seed), automatic: true }
    let busy = 0
    for (let i = 0; i < 400; i++) {
      state = advanceSimulation(state)
      busy += Number(state.timeline.at(-1).pid !== null)
      assert.equal(state.busyTicks, busy)
      assert.equal(state.tick, i + 1)
      assert.ok(state.processes.filter(p => p.state === 'running').length <= 1)
      assert.equal(new Set(state.processes.map(p => p.pid)).size, state.processes.length)
      assert.ok(state.processes.length <= MAX_PROCESSES)
      assert.equal(state.completed + state.processes.length, state.nextPid - 101)
      assert.ok(state.processes.every(p => p.remaining > 0 && p.remaining <= p.total))
      assert.ok(state.timeline.length <= 24 && state.events.length <= 10)
    }
  }
})
test('manual additions respect cap and all initial sessions eventually complete', () => {
  let state = resetSimulation(42)
  for (let i = 0; i < 30; i++) state = simulationReducer(state, { type: 'add' })
  assert.equal(state.processes.length, MAX_PROCESSES)
  for (let i = 0; i < 400; i++) state = advanceSimulation(state)
  assert.equal(state.completed, MAX_PROCESSES)
  assert.equal(state.processes.length, 0)
})

const act = (state, type, extra = {}) => simulationReducer(state, { type, ...extra })
const manualSession = (...processes) => act(session(...processes), 'mode', { value: 'manual' })
test('manual three-process lesson: step, request I/O, step, complete slot, FIFO', () => {
  let state = manualSession(process(101), process(102), process(103))
  state = act(state, 'step')
  assert.equal(state.processes.find(p => p.pid === 101).remaining, 6)
  const snapshot = structuredClone(state)
  state = act(state, 'request-io')
  assert.equal(snapshot.processes.find(p => p.pid === 101).state, 'running')
  assert.equal(state.processes.find(p => p.pid === 101).state, 'blocked')
  assert.equal(state.processes.filter(p => p.state === 'running').length, 0)
  assert.equal(state.tick, 1)
  assert.ok(['Teclado', 'Disco', 'Red', 'Impresora'].includes(state.processes.find(p => p.pid === 101).ioType))
  state = act(state, 'step')
  assert.equal(state.processes.find(p => p.pid === 102).state, 'running')
  state = act(state, 'complete-slot', { slot: 0 })
  assert.equal(state.processes.find(p => p.pid === 101).state, 'ready')
  assert.equal(state.tick, 2)
  state = act(act(state, 'step'), 'step')
  assert.equal(state.processes.find(p => p.pid === 102).state, 'ready')
  state = act(state, 'step')
  assert.equal(state.processes.find(p => p.pid === 103).state, 'running')
  assert.deepEqual(state.timeline.map(t => t.pid), [101, 102, 102, 102, 103])
})
test('manual mode suppresses clock, scheduled I/O and automatic arrivals', () => {
  let state = { ...manualSession(process(101, { ioAt: 1 })), automatic: true }
  assert.equal(act(state, 'clock'), state)
  assert.equal(act(state, 'toggle'), state)
  for (let i = 0; i < 6; i++) state = act(state, 'step')
  assert.equal(state.processes.length, 1)
  assert.equal(state.processes[0].remaining, 1)
  assert.equal(state.processes[0].ioAt, 1)
  assert.equal(state.busyTicks, 6)
})
test('manual I/O never expires on ticks; completing it leaves CPU free', () => {
  let state = act(act(manualSession(process(101)), 'step'), 'request-io')
  for (let i = 0; i < 10; i++) state = act(state, 'step')
  assert.equal(state.processes[0].state, 'blocked')
  assert.equal(state.processes[0].ioRemaining, 2)
  assert.equal(state.busyTicks, 1)
  assert.ok(state.timeline.slice(1).every(t => t.pid === null))
  state = act(state, 'complete-io', { pid: 101 })
  assert.equal(state.processes[0].state, 'ready')
  assert.equal(state.processes[0].quantumUsed, 0)
  assert.equal(state.tick, 11)
})
test('mode changes preserve process state and resume I/O timing in automatic mode', () => {
  let state = act(act(manualSession(process(101)), 'step'), 'request-io')
  const snapshot = structuredClone(state)
  state = act(state, 'mode', { value: 'automatic' })
  assert.deepEqual(state.processes, snapshot.processes)
  assert.deepEqual(state.timeline, snapshot.timeline)
  assert.equal(state.active, false)
  state = act(act(state, 'toggle'), 'clock')
  assert.equal(state.processes[0].ioRemaining, 1)
  state = act(state, 'clock')
  assert.equal(state.processes[0].state, 'running')
  state = act(state, 'mode', { value: 'manual' })
  assert.equal(act(state, 'clock'), state)
  const reset = act(state, 'reset', { value: 77 })
  assert.equal(reset.mode, 'manual')
  assert.equal(reset.tick, 0)
})
test('invalid I/O commands cannot resurrect finished processes or change Ready processes', () => {
  let state = manualSession(process(101, { total: 1, remaining: 1 }))
  assert.equal(act(state, 'request-io'), state)
  assert.equal(act(state, 'complete-io', { pid: 101 }), state)
  state = act(state, 'step')
  assert.equal(state.completed, 1)
  assert.equal(act(state, 'complete-io', { pid: 101 }), state)
  assert.equal(act(state, 'complete-slot', { slot: 8 }), state)
})
test('blocked keyboard slots reflect current order and buttons can complete beyond nine', () => {
  let state = manualSession(...Array.from({ length: 12 }, (_, i) => process(101 + i, { state: 'blocked', ioRemaining: 2 })))
  state = act(state, 'complete-slot', { slot: 1 })
  assert.equal(state.processes.find(p => p.pid === 102).state, 'ready')
  state = act(state, 'complete-slot', { slot: 1 })
  assert.equal(state.processes.find(p => p.pid === 103).state, 'ready')
  state = act(state, 'complete-io', { pid: 112 })
  assert.equal(state.processes.find(p => p.pid === 112).state, 'ready')
})
